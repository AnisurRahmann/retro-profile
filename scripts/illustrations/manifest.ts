import { gzipSync } from "node:zlib";

export interface PartMeta {
  name: string;
  viewBox: string;
  width: number;
  height: number;
  origin: [number, number];
  pivot: [number, number];
  z: number;
  bytes: number;
}

export interface AssetMeta {
  id: string;
  source: string;
  format: "svg" | "webp";
  bytes: number;
  gzipBytes: number;
  parts: PartMeta[];
}

/** Sizes for one object: the sum of its part files, raw and gzipped together (how they travel inside the page). */
export function assetMeta(id: string, source: string, format: "svg" | "webp", parts: PartMeta[], payloads: (string | Uint8Array)[]): AssetMeta {
  const joined = Buffer.concat(payloads.map((payload) => Buffer.from(payload)));
  return {
    id,
    source,
    format,
    bytes: joined.byteLength,
    gzipBytes: format === "svg" ? gzipSync(joined).byteLength : joined.byteLength,
    parts: [...parts].sort((a, b) => a.z - b.z || a.name.localeCompare(b.name)),
  };
}

const HEADER = "// Generated by `pnpm illustrations`. Do not edit: change the raw sheet or assets/illustrations/parts/*.json and run it again.\n";

/** Stage g. The typed manifest module, parsed by the zod schema at import like the rest of the content. */
export function manifestModule(assets: AssetMeta[]): string {
  const sorted = [...assets].sort((a, b) => a.id.localeCompare(b.id));
  const body = JSON.stringify(Object.fromEntries(sorted.map((asset) => [asset.id, asset])), null, 2);
  return `${HEADER}import { illustrationManifestSchema } from "@/schema";\n\nexport const manifest = illustrationManifestSchema.parse(${body});\n`;
}

/** The traced layers of one object as a module, so server components inline them without reading files. */
export function pathsModule(id: string, parts: { name: string; paths: [string, string][] }[]): string {
  const lines = parts
    .map(({ name, paths }) => `  ${JSON.stringify(name)}: [\n${paths.map(([cls, d]) => `    [${JSON.stringify(cls)}, ${JSON.stringify(d)}],`).join("\n")}\n  ],`)
    .join("\n");
  return `${HEADER}import type { IllustrationPaths } from "@/schema";\n\nexport const ${id}: IllustrationPaths = {\n${lines}\n};\n`;
}
